import assert from'node:assert/strict';
import{V38_POOL_SHORTLIST_V2,buildFinalReviewQueue}from'./v38-pool-shortlist-v2.mjs';
const retained=(id,layer,support=0)=>({player_id:id,pool_layer:layer,gate_count:layer==='CORE'?6:5,shortlist:{status:'RETAIN_FOR_FINAL_REVIEW',support_count:support,flags:{preferred_market:support>0,confirmed_lineup:support>1,bbe_support:support>2,exact_side_park:support>3}}});
const rows=[];
for(let i=1;i<=2;i++)rows.push(retained(i,'CORE',4));
for(let i=3;i<=32;i++)rows.push(retained(i,'PROTECTED_POOL',i%4));
for(let i=33;i<=42;i++)rows.push(retained(i,'QUALITY_VALUE_POOL',i%4));
for(let i=43;i<=50;i++)rows.push(retained(i,'ESCAPE_WATCH',4));
const q=buildFinalReviewQueue(rows);
const count=l=>q.queue.filter(r=>r.pool_layer===l).length;
assert.equal(V38_POOL_SHORTLIST_V2.cumulative_layer_caps.through_protected,14);
assert.equal(V38_POOL_SHORTLIST_V2.cumulative_layer_caps.through_quality,23);
assert.equal(V38_POOL_SHORTLIST_V2.cumulative_layer_caps.with_escape,25);
assert.equal(count('CORE'),2);
assert.equal(count('CORE')+count('PROTECTED_POOL'),14);
assert.equal(count('CORE')+count('PROTECTED_POOL')+count('QUALITY_VALUE_POOL'),23);
assert.equal(q.queue.length,25);
assert.equal(q.pool_target_forced,false);
const sparse=buildFinalReviewQueue([retained(1,'CORE',4),retained(2,'PROTECTED_POOL',2),retained(3,'QUALITY_VALUE_POOL',2)]);
assert.equal(sparse.queue.length,3);
assert.equal(sparse.pool_target_forced,false);
console.log('V38_POOL_QUEUE_CAPS_PASS');
